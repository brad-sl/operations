def generate_candidates(pair: str):
    """Generate a rich set of candidates to test for a pair."""
    ticker = pair.split("-")[0].upper()
    lower = ticker.lower()
    candidates = {
        f"{ticker} (ticker)": ticker,
        f"${ticker} (dollar)": f"${ticker}",
        f"{lower} (lower)": lower,
    }

    names = FORMAL_NAME_MAP.get(pair, [lower])
    for name in names:
        if name != lower:
            candidates[f"{name} (name)"] = name

    # Test explicit OR for controversial cases
    if pair == "XRP-USD":
        candidates["XRP OR ripple"] = "XRP OR ripple"
        candidates["$XRP OR ripple"] = "$XRP OR ripple"

    if pair == "BTC-USD":
        candidates["BTC OR bitcoin"] = "BTC OR bitcoin"

    return candidates

def fetch_x_for_candidates(bearer: str, candidates: dict, max_results: int = 10):
    """Test each candidate on X recent search. Returns scored results."""
    import requests
    results = {}
    url = "https://api.twitter.com/2/tweets/search/recent"
    headers = {"Authorization": f"Bearer {bearer}"}

    for label, query in candidates.items():
        params = {
            "query": f"{query} -scam -is:retweet",
            "max_results": min(max_results, 10),
            "tweet.fields": "text,public_metrics",
        }
        try:
            resp = requests.get(url, headers=headers, params=params, timeout=15)
            if resp.status_code != 200:
                results[label] = {"count": 0, "trading_score": 0, "ratio": 0, "sample": f"API error {resp.status_code}", "query": query}
                continue

            posts = resp.json().get("data", []) or []
            count = len(posts)

            total_trading = 0
            for p in posts:
                text = p.get("text", "")
                total_trading += count_trading_relevance(text)

            ratio = total_trading / max(1, count) if count else 0
            sample = posts[0].get("text", "")[:110].replace("\n", " ") if posts else "(no posts)"

            results[label] = {
                "count": count,
                "trading_score": total_trading,
                "ratio": round(ratio, 2),
                "sample": sample,
                "query": query
            }
        except Exception as e:
            results[label] = {"count": 0, "trading_score": 0, "ratio": 0, "sample": str(e)[:60], "query": query}

    return results

def main():
    print("Sentiment Keyword Optimizer Tool")
    print(f"Timestamp: {datetime.utcnow().isoformat()}")
    print("Goal: Find keywords that surface the strongest *trading-relevant* signals (price action, slang, conviction) for accurate decisions.")
    print("Lexicon: Base validated + heavy crypto-specific slang weighting.\n")

    bearer = load_bearer_token()
    if not bearer:
        print("❌ No X_API_BEARER token found. Cannot run X tests.")
        sys.exit(1)

    pairs = load_current_basket()
    print(f"Testing basket ({len(pairs)} pairs): {pairs}\n")

    all_results = {}

    for pair in pairs:
        print(f"\n=== {pair} ===")
        candidates = generate_candidates(pair)
        x_results = fetch_x_for_candidates(bearer, candidates, max_results=10)

        # Pick best by trading_score (primary), then ratio, then volume
        best_label = max(x_results.items(), key=lambda x: (x[1]["trading_score"], x[1]["ratio"], x[1]["count"]))[0]
        best = x_results[best_label]

        print(f"  Best: {best_label}")
        print(f"    Posts: {best['count']} | Trading score: {best['trading_score']} | Ratio: {best['ratio']}")
        print(f"    Sample: {best['sample']}")

        all_results[pair] = {
            "candidates": x_results,
            "recommendation": {
                "best_label": best_label,
                "best_query": best["query"],
                "trading_score": best["trading_score"],
                "posts": best["count"],
                "ratio": best["ratio"]
            }
        }

    # Summary table
    print("\n\n=== RECOMMENDATIONS (sorted by trading signal strength) ===")
    sorted_pairs = sorted(all_results.items(), key=lambda x: x[1]["recommendation"]["trading_score"], reverse=True)
    for pair, data in sorted_pairs:
        rec = data["recommendation"]
        print(f"{pair:12s} → {rec['best_label']:25s} (score={rec['trading_score']:3d}, posts={rec['posts']:2d}, ratio={rec['ratio']})")

    # Save detailed report
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(REPORT_PATH, "w") as f:
        json.dump({
            "timestamp": datetime.utcnow().isoformat(),
            "basket": pairs,
            "lexicon_note": "Base validated lexicons + crypto slang (moon/pump/ATH/FUD/rug/rekt etc.) weighted heavily for trading intensity.",
            "results": all_results,
            "note": "Use the 'best_query' values to update KEYWORD_MAP / pair_keywords in the fetch scripts."
        }, f, indent=2)

    print(f"\nDetailed report saved to {REPORT_PATH}")
    print("\nNext steps:")
    print("- Review samples for qualitative quality.")
    print("- Run with --apply (future) or manually patch the fetch scripts with the best queries.")
    print("- Re-run periodically as crypto language evolves.")



