def count_trading_relevance(text: str) -> int:
    """Returns how many trading-relevant tokens are in the text (higher = stronger signal)."""
    text_lower = text.lower()
    score = 0
    for word in ALL_TRADING_WORDS:
        if word in text_lower:
            score += 1
    # Bonus for strong crypto slang
    strong_slant = ["moon", "pump", "ath", "fud", "rug", "rekt", "wagmi", "🚀"]
    for w in strong_slant:
        if w in text_lower:
            score += 1
    return score

