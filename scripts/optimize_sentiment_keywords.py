def load_and_merge_keywords(new_recommendations: dict):
    """Merge optimizer results into the central config file."""
    keywords_file = BASE_DIR / "config" / "sentiment_keywords.json"
    if keywords_file.exists():
        with open(keywords_file) as f:
            data = json.load(f)
    else:
        data = {"version": 1, "pairs": {}}

    data["last_updated"] = datetime.utcnow().isoformat() + "Z"
    data["method"] = "Updated via scripts/optimize_sentiment_keywords.py (trading relevance scoring)"

    for pair, rec in new_recommendations.items():
        if pair not in data["pairs"]:
            data["pairs"][pair] = {}
        data["pairs"][pair]["x"] = rec.get("x", rec.get("best_query", _get_ticker(pair)))
        data["pairs"][pair]["reddit"] = rec.get("reddit", [rec.get("best_query", _get_ticker_lower(pair))])
        data["pairs"][pair]["notes"] = rec.get("notes", "Generated by optimizer tool")

    keywords_file.parent.mkdir(parents=True, exist_ok=True)
    with open(keywords_file, "w") as f:
        json.dump(data, f, indent=2)
    print(f"Updated central keywords file: {keywords_file}")
    return data

